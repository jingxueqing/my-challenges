# --------------------------------------------------------------------------
# 索引（首次 import 时构建，之后只读）
# --------------------------------------------------------------------------
TAG_INDEX: Dict[str, Tag] = {t.id: t for t in _TAGS}
KEYWORD_INDEX: Dict[str, List[str]] = {}  # keyword(lower) -> [tag_id]

for _t in _TAGS:
    for _kw in _t.all_keywords():
        KEYWORD_INDEX.setdefault(_kw.lower(), []).append(_t.id)


def get_tag(tag_id: str) -> Tag:
    try:
        return TAG_INDEX[tag_id]
    except KeyError as exc:
        raise KeyError(f"未知标签 id: {tag_id}（标签一经发布不得改名，新增请用新 id）") from exc


def tags_in_domain(domain: str) -> List[Tag]:
    if domain not in DOMAINS:
        raise ValueError(f"未知域: {domain}，合法值: {DOMAINS}")
    return [t for t in _TAGS if t.domain == domain]


def all_tags() -> List[Tag]:
    return list(_TAGS)


def long_keywords(min_len: int = 3) -> List[str]:
    """按长度倒序返回关键词，供 parser 做「最长匹配优先」。

    必要性：'Python' 同时属于 ENG01 与 DAT06，若短匹配优先会双计。
    """
    kws = [k for k in KEYWORD_INDEX if len(k) >= min_len]
    return sorted(kws, key=len, reverse=True)


def stats() -> Dict[str, object]:
    """自检用：标签总数、每域标签数、关键词总数。"""
    per_domain = {d: len(tags_in_domain(d)) for d in DOMAINS}
    return {
        "tags": len(_TAGS),
        "domains": per_domain,
        "keywords": len(KEYWORD_INDEX),
    }
